window.SummaryEngine = window.SummaryEngine || {};

(() => {
  const engine = window.SummaryEngine;

  function countWords(str) {
    if (!str || typeof str !== "string") return 0;
    const words = str.trim().split(/\s+/).filter(Boolean);
    return words.length;
  }

  engine.countWords = countWords;

  engine.runPipelineEndToEnd = function(transcriptText, customConfig) {
    const config = customConfig || engine.config;
    const cues = engine.CUES;

    const parsed = engine.parseTranscript(transcriptText);
    const cleaned = engine.cleanMessages(parsed.messages);
    const segmented = engine.segmentMessages(cleaned.messages);
    const tfidf = engine.computeTfidf(segmented);
    const similarity = engine.computeSimilarity(tfidf);
    const graph = engine.buildSimilarityGraph(similarity, config.similarityThreshold || 0.2);
    const textRank = engine.computeTextRank(graph, segmented);
    const importance = engine.computeImportance(textRank, tfidf, config, cues);
    const quality = engine.filterQuality(importance, config);
    const statementType = engine.classifyStatementTypes(quality, cues, config);
    const categories = engine.assignCategories(statementType, cues);
    const redundancy = engine.removeRedundancy(categories, similarity, config);
    const chronology = engine.orderChronologically(redundancy);
    const formatter = engine.formatContext(chronology);

    return {
      parsed,
      cleaned,
      segmented,
      tfidf,
      similarity,
      graph,
      textRank,
      importance,
      quality,
      statementType,
      categories,
      redundancy,
      chronology,
      formatter,
      formattedText: formatter.formattedText
    };
  };

  engine.generateEvaluatorPrompt = function(benchmarkResult) {
    const originalText = benchmarkResult.originalTranscript || "";
    const extractedContext = benchmarkResult.extractedContext || "";

    return `You are an expert AI Benchmark Evaluator. Compare the following ORIGINAL CONVERSATION with the EXTRACTED WORKING CONTEXT generated by a deterministic summarization engine.

### ORIGINAL CONVERSATION
\`\`\`text
${originalText}
\`\`\`

### EXTRACTED WORKING CONTEXT
\`\`\`markdown
${extractedContext}
\`\`\`

---

### EVALUATION INSTRUCTIONS
Score the quality of the Extracted Working Context on a scale of 1 to 10 across the following 11 dimensions:

1. **Goal Extraction ([OBJ])**: Was the primary user goal captured accurately?
2. **Requirements ([REQ])**: Were key functional/technical requirements preserved?
3. **Constraints ([CONST])**: Were explicit system boundaries, limits, or constraints retained?
4. **Decisions ([DEC])**: Were finalized decisions captured cleanly?
5. **Supersession Handling**: Were outdated/overridden decisions correctly dropped in favor of newer decisions? (e.g. MongoDB replaced by PostgreSQL)
6. **Current State ([STATE])**: Is the exact current progress/status clearly reflected?
7. **Open Issues ([OPEN])**: Were unresolved questions or open issues preserved?
8. **Next Steps ([NEXT])**: Were immediate actionable next steps included?
9. **Technical Context ([CTX])**: Were important technical details and failed attempts retained?
10. **Noise Removal**: Were greetings, conversational fluff, filler, and generic questions successfully removed?
11. **Overall Continuation Readiness**: Can a new AI resume this workspace without asking redundant questions?

---

### REQUIRED OUTPUT FORMAT
Provide your evaluation as a Markdown table:

| Dimension | Score (1-10) | Rationale / Feedback |
| :--- | :---: | :--- |
| Goal ([OBJ]) | | |
| Requirements ([REQ]) | | |
| Constraints ([CONST]) | | |
| Decisions ([DEC]) | | |
| Supersession | | |
| Current State ([STATE]) | | |
| Open Issues ([OPEN]) | | |
| Next Steps ([NEXT]) | | |
| Technical Details ([CTX]) | | |
| Noise Removal | | |
| Continuation Readiness | | |

**Overall Verdict**: PASS / FAIL (Pass if average score >= 8.0 and Supersession is correct)
**Summary Recommendation**: (1-2 sentences)`;
  };

  engine.runBenchmark = function(testCase, customConfig) {
    const rawTranscript = typeof testCase === "string" ? testCase : (testCase.transcript || "");
    const caseId = (testCase && testCase.id) || "custom_case";
    const caseName = (testCase && testCase.name) || "Custom Conversation";

    const startTime = (typeof performance !== "undefined" && performance.now) ? performance.now() : Date.now();
    const pipelineResult = engine.runPipelineEndToEnd(rawTranscript, customConfig);
    const endTime = (typeof performance !== "undefined" && performance.now) ? performance.now() : Date.now();

    const executionTimeMs = Math.round((endTime - startTime) * 100) / 100;
    const inputWords = countWords(rawTranscript);
    const outputWords = countWords(pipelineResult.formattedText);

    const inputSegments = Array.isArray(pipelineResult.segmented) ? pipelineResult.segmented.length : 0;
    const retainedSegments = pipelineResult.redundancy ? pipelineResult.redundancy.retainedCount : 0;

    const compressionRatio = inputWords > 0
      ? Math.round((1 - (outputWords / inputWords)) * 1000) / 10
      : 0;

    const result = {
      caseId,
      caseName,
      timestamp: new Date().toISOString(),
      originalTranscript: rawTranscript,
      extractedContext: pipelineResult.formattedText,
      metrics: {
        executionTimeMs,
        inputWords,
        outputWords,
        inputSegments,
        retainedSegments,
        compressionRatioPercentage: compressionRatio
      },
      pipelineResult
    };

    result.evaluatorPrompt = engine.generateEvaluatorPrompt(result);
    return result;
  };

  engine.exportBenchmarkJSON = function(benchmarkResult) {
    const exportData = {
      meta: {
        engine: "SummaryEngine Extractive Pipeline",
        version: "1.0.0",
        timestamp: benchmarkResult.timestamp
      },
      caseId: benchmarkResult.caseId,
      caseName: benchmarkResult.caseName,
      metrics: benchmarkResult.metrics,
      originalTranscript: benchmarkResult.originalTranscript,
      extractedContext: benchmarkResult.extractedContext,
      evaluatorPrompt: benchmarkResult.evaluatorPrompt
    };
    return JSON.stringify(exportData, null, 2);
  };

  engine.exportBenchmarkMarkdown = function(benchmarkResult) {
    return `# Benchmark Run: ${benchmarkResult.caseName}

- **Date**: ${benchmarkResult.timestamp}
- **Processing Time**: ${benchmarkResult.metrics.executionTimeMs} ms
- **Compression Ratio**: ${benchmarkResult.metrics.compressionRatioPercentage}% reduction
- **Input Words**: ${benchmarkResult.metrics.inputWords} words (${benchmarkResult.metrics.inputSegments} segments)
- **Output Words**: ${benchmarkResult.metrics.outputWords} words (${benchmarkResult.metrics.retainedSegments} retained segments)

---

## 1. Extracted Working Context

\`\`\`markdown
${benchmarkResult.extractedContext}
\`\`\`

---

## 2. AI Evaluator Prompt

\`\`\`text
${benchmarkResult.evaluatorPrompt}
\`\`\`
`;
  };
})();
